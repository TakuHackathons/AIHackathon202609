type ContextValue = {
  locale: AdminLocale;
  setLocale: (locale: AdminLocale) => void;
  t: (key: AdminTranslationKey, params?: Params) => string;
};
const Context = createContext<ContextValue | null>(null);
const storageKey = 'selected_locale';

export function resolveAdminLocale(stored: string | null, languages: readonly string[]): AdminLocale {
  let selected: string | null = stored;
  try {
    selected = stored ? JSON.parse(stored) : null;
  } catch {
    // Accept values stored by older versions without JSON encoding.
  }
  if (selected === 'ja' || selected === 'en') return selected;
  for (const language of languages) {
    if (language?.toLowerCase().startsWith('ja')) return 'ja';
    if (language?.toLowerCase().startsWith('en')) return 'en';
  }
  return 'ja';
}

export function AdminLocaleProvider({ children }: { children: ReactNode }) {
  const [locale, updateLocale] = useState<AdminLocale>('ja');
  useEffect(() => {
    const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
    updateLocale(resolveAdminLocale(localStorage.getItem(storageKey), languages));
  }, []);
  const setLocale = (next: AdminLocale) => {
    updateLocale(next);
    localStorage.setItem(storageKey, JSON.stringify(next));
  };
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const value = useMemo<ContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, params) =>
        Object.entries(params ?? {}).reduce(
          (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
          (locale === 'ja' ? ja : en)[key],
        ),
    }),
    [locale],
  );
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useAdminI18n() {
  const value = useContext(Context);
  if (!value) throw new Error('AdminLocaleProvider is required.');
  return value;
}

export function AdminLocaleSwitch() {
  const { locale, setLocale, t } = useAdminI18n();
  return (
    <label className="admin-locale-switch">
      {t('language.switch')}
      <select value={locale} onChange={(event) => setLocale(event.target.value as AdminLocale)}>
        <option value="ja">{t('language.ja')}</option>
        <option value="en">{t('language.en')}</option>
      </select>
    </label>
  );
}
